"""Write `docs/content/error-codes.md` from the tables the surfaces actually use.

**Generated rather than curated**, for the reason `export_mcp_tools.py` gives: a
refusal's `code` is what a client branches on, and a hand-written reference to
~100 of them is a second copy free to drift from `kernel/error_codes.py`. Every
column is read from where the running code keeps it:

- the **code** from `ERROR_CODES` (`kernel/error_codes.py`);
- the **status** from `ERROR_RULES` (`server/errors.py`) — what REST answers;
- the **meaning** from the exception class's own docstring, first sentence;
- the **remedy** from the MCP hint table, else the CLI's;
- **`retry_with`** from the MCP envelope's table — the parameter that turns the
  same call into one that succeeds. Most refusals have none.

Usage:

    uv run python scripts/export_error_codes.py            # write it
    uv run python scripts/export_error_codes.py --check     # fail if stale
"""

from __future__ import annotations

import inspect
import re
import sys
from pathlib import Path

from visionset.cli._errors import _HINTS as CLI_HINTS
from visionset.kernel.error_codes import ERROR_CODES
from visionset.mcp._errors import _HINTS as MCP_HINTS
from visionset.mcp._errors import RETRY_WITH
from visionset.server.errors import ERROR_RULES

REPO_ROOT = Path(__file__).resolve().parent.parent

OUTPUT_PATH = REPO_ROOT / "docs" / "content" / "error-codes.md"

BANNER = """<!-- Generated by scripts/export_error_codes.py. Do not edit by hand. -->
# Error codes

Every refusal carries a stable `code`, over REST, in the CLI's `--json` output and in the MCP
error envelope alike. Branch on the code, never on the sentence. This table is generated from the
tables the surfaces use, so it cannot drift from what they answer.

- **Status** is what REST answers. The CLI exits 1 and MCP returns an error envelope for every
  one of them; see [api.md](api.md#the-error-body) for what decides each status.
- **Meaning** is the first sentence of the error's own description in the kernel.
- **Remedy** is what a caller can do about it, where there is something specific to say. Most
  messages already carry their own remedy, so a blank here is not a gap.
- **Retry with** names the parameter that turns the same call into one that succeeds. Nothing else
  is retryable as it stands.

The framework's own codes - `VALIDATION_ERROR`, `NOT_FOUND`, `METHOD_NOT_ALLOWED`, `UNAUTHORIZED`
and `INTERNAL_ERROR` - are not raised by the kernel and are described in [api.md](api.md).
"""

_SENTENCE = re.compile(r"(?<=[.!?])\s")
_MAX_MEANING = 240


def _walk(table: dict[type[BaseException], str], cls: type[BaseException]) -> str | None:
    for ancestor in cls.__mro__:
        found = table.get(ancestor)
        if found is not None:
            return found
    return None


def _cell(text: str | None) -> str:
    if not text:
        return ""
    return " ".join(text.split()).replace("|", "\\|")


def _meaning(cls: type[BaseException]) -> str:
    paragraph = (inspect.getdoc(cls) or "").split("\n\n")[0]
    sentence = _SENTENCE.split(" ".join(paragraph.split()), maxsplit=1)[0]
    if len(sentence) > _MAX_MEANING:
        sentence = sentence[: _MAX_MEANING - 1].rstrip() + "…"
    return sentence


def _status(cls: type[BaseException]) -> str:
    for ancestor in cls.__mro__:
        rule = ERROR_RULES.get(ancestor)  # type: ignore[call-overload]
        if rule is not None:
            return str(rule.status)
    return "500"


def render() -> str:
    lines = [BANNER, f"{len(ERROR_CODES)} codes, alphabetical.\n"]
    lines.append("| Code | Status | Meaning | Remedy | Retry with |")
    lines.append("| --- | --- | --- | --- | --- |")
    for cls, code in sorted(ERROR_CODES.items(), key=lambda item: item[1]):
        remedy = _walk(MCP_HINTS, cls) or _walk(CLI_HINTS, cls)
        retry = _walk(RETRY_WITH, cls)
        lines.append(
            f"| `{code}` | {_status(cls)} | {_cell(_meaning(cls))} | {_cell(remedy)} | "
            f"{f'`{retry}`' if retry else ''} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    rendered = render()
    if "--check" in argv:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.exists() else ""
        if current != rendered:
            print(
                f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale — run "
                f"`uv run python scripts/export_error_codes.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} matches the error tables.")
        return 0
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {OUTPUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

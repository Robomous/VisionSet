"""Write the format verification table in `docs/content/architecture/backend/formats.md`.

Generated for the reason `export_target_catalog.py` gives: the matrix is the
installed plugins joined with `src/visionset/formats/verification.json`, every
surface renders that join, and a hand-written copy would drift from the one
`GET /formats/matrix` serves. Only the region between the two markers is owned
here.

Usage:

    uv run python scripts/export_format_matrix.py            # rewrite the region
    uv run python scripts/export_format_matrix.py --check     # fail if stale
"""

from __future__ import annotations

import sys
from pathlib import Path

from visionset.formats.matrix import COUNTING_GATES, Evidence, MatrixRow, build
from visionset.formats.registry import exporters, importers

REPO_ROOT = Path(__file__).resolve().parent.parent

DOCUMENT_PATH = REPO_ROOT / "docs" / "content" / "architecture" / "backend" / "formats.md"

BEGIN = "<!-- format-matrix:begin — generated by scripts/export_format_matrix.py; do not edit -->"
END = "<!-- format-matrix:end -->"

COLUMNS = (
    "Format",
    "Direction",
    "Task and dialect",
    "Geometries",
    "Degraded",
    "Lossy",
    "Status",
    "Evidence",
)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("<", "&lt;")


def _evidence(row: MatrixRow) -> str:
    def label(one: Evidence) -> str:
        name = one.kind.replace("_", " ")
        if one.reader is None:
            return name
        group = f", `{one.requires}` group" if one.requires else ""
        return f"{name} ({one.reader}{group})"

    counted = list(dict.fromkeys(label(one) for one in row.evidence if one.gate in COUNTING_GATES))
    opt_in = list(
        dict.fromkeys(label(one) for one in row.evidence if one.gate not in COUNTING_GATES)
    )
    parts = counted or ["—"]
    if opt_in:
        parts.append("opt-in: " + ", ".join(opt_in))
    return "; ".join(parts)


def render() -> str:
    """The region between the markers, markers included."""
    matrix = build(exporters(), importers())
    lines = [
        BEGIN,
        "| " + " | ".join(COLUMNS) + " |",
        "| " + " | ".join("---" for _ in COLUMNS) + " |",
    ]
    for row in matrix.rows:
        name = f"`{row.format}`" + "".join(f" (alias `{one}`)" for one in row.aliases)
        task = row.task or "—"
        if row.dialects:
            task += ": " + "; ".join(row.dialects)
        lossy = "—" if row.lossy is None else ("yes" if row.lossy else "no")
        lines.append(
            "| "
            + " | ".join(
                _cell(one)
                for one in (
                    name,
                    row.direction,
                    task,
                    ", ".join(row.geometries) or "—",
                    ", ".join(row.degraded_geometries) or "—",
                    lossy,
                    row.status.replace("_", " "),
                    _evidence(row),
                )
            )
            + " |"
        )
    lines.append(END)
    return "\n".join(lines)


def _split(document: str) -> tuple[str, str, str]:
    """The text before the region, the region, and the text after it."""
    start = document.index(BEGIN)
    stop = document.index(END, start) + len(END)
    return document[:start], document[start:stop], document[stop:]


def main(argv: list[str]) -> int:
    document = DOCUMENT_PATH.read_text(encoding="utf-8")
    before, current, after = _split(document)
    rendered = render()
    relative = DOCUMENT_PATH.relative_to(REPO_ROOT)
    if "--check" in argv:
        if current != rendered:
            print(
                f"the format matrix in {relative} is stale — run "
                f"`uv run python scripts/export_format_matrix.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"the format matrix in {relative} matches the installed formats.")
        return 0
    DOCUMENT_PATH.write_text(before + rendered + after, encoding="utf-8")
    print(f"wrote the format matrix in {DOCUMENT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

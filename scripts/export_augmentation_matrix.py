"""Write the augmentation compatibility table in `docs/content/preprocessing.md` from the resolver.

**Generated rather than curated**, for `export_target_catalog.py`'s reason: the
table is what `augmentation_matrix` answers, and a hand-written copy would be a
second registry free to drift from the one an export refuses by. Only the
region between the two markers is owned here; the prose around it stays the
author's.

Usage:

    uv run python scripts/export_augmentation_matrix.py            # rewrite the region
    uv run python scripts/export_augmentation_matrix.py --check     # fail if stale
"""

from __future__ import annotations

import sys
from pathlib import Path

from visionset.kernel.domain import (
    GEOMETRY_TASKS,
    KIND_LABELS,
    LabelKind,
    MatrixCell,
    ReasonCode,
    Task,
    Verdict,
    augment_operations,
    augmentation_matrix,
)

REPO_ROOT = Path(__file__).resolve().parent.parent

DOCUMENT_PATH = REPO_ROOT / "docs" / "content" / "preprocessing.md"

BEGIN = (
    "<!-- augmentation-matrix:begin — generated by scripts/export_augmentation_matrix.py; "
    "do not edit -->"
)
END = "<!-- augmentation-matrix:end -->"


def _label(kind: LabelKind) -> str:
    label = KIND_LABELS[kind]
    if label is None:
        return f"{kind.value} (gated)"
    geometry, modality = label
    return f"{kind.value} (`{geometry.value}` on {modality})"


def _reasons(reasons: tuple[ReasonCode, ...]) -> str:
    return ", ".join(f"`{reason.value}`" for reason in reasons)


def _cell(base: MatrixCell, refused_for: list[Task]) -> str:
    text = (
        "supported" if base.verdict is Verdict.SUPPORTED else f"refused: {_reasons(base.reasons)}"
    )
    if refused_for:
        text += f"; `task_unsupported` for {', '.join(task.value for task in refused_for)}"
    return text


def render() -> str:
    """The region between the markers, markers included."""
    operations = augment_operations()
    base = {(cell.kind, cell.op, cell.version): cell for cell in augmentation_matrix()}
    by_task = {
        task: {
            (cell.kind, cell.op, cell.version): cell
            for cell in augmentation_matrix(frozenset({task}))
        }
        for task in Task
    }
    columns = ["Label", *(f"`{one.op.value}` v{one.version}" for one in operations)]
    lines = [
        BEGIN,
        "| " + " | ".join(columns) + " |",
        "| " + " | ".join("---" for _ in columns) + " |",
    ]
    for kind in LabelKind:
        cells = []
        for operation in operations:
            key = (kind, operation.op.value, operation.version)
            label = KIND_LABELS[kind]
            fed = frozenset() if label is None else GEOMETRY_TASKS[label[0]]
            refused_for = [
                task
                for task in Task
                if task in fed and ReasonCode.TASK_UNSUPPORTED in by_task[task][key].reasons
            ]
            cells.append(_cell(base[key], refused_for))
        lines.append("| " + " | ".join([_label(kind), *cells]) + " |")
    lines.append(END)
    return "\n".join(lines)


def _split(document: str) -> tuple[str, str, str]:
    """The text before the region, the region, and the text after it."""
    start = document.index(BEGIN)
    stop = document.index(END, start) + len(END)
    return document[:start], document[start:stop], document[stop:]


def main(argv: list[str]) -> int:
    document = DOCUMENT_PATH.read_text(encoding="utf-8")
    before, current, after = _split(document)
    rendered = render()
    relative = DOCUMENT_PATH.relative_to(REPO_ROOT)
    if "--check" in argv:
        if current != rendered:
            print(
                f"the augmentation matrix in {relative} is stale — run "
                f"`uv run python scripts/export_augmentation_matrix.py` and commit the result.",
                file=sys.stderr,
            )
            return 1
        print(f"the augmentation matrix in {relative} matches the resolver.")
        return 0
    DOCUMENT_PATH.write_text(before + rendered + after, encoding="utf-8")
    print(f"wrote the augmentation matrix in {DOCUMENT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
